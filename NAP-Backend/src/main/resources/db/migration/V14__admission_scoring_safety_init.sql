-- Admission scoring safety and instrumentation.
--
-- Flyway is disabled in application.yaml (schema is currently maintained by
-- Hibernate ddl-auto=update), so these statements are kept in step with the JPA
-- entities and apply automatically once Flyway is switched on.

-- Pass mark on the 0-100 admission index. Deliberately NULL: a programme with no
-- threshold routes every applicant to manual review instead of admitting them.
-- The legacy cutoff_score column is left untouched because its units differ from
-- this scale and reusing the number would silently reinterpret every threshold.
ALTER TABLE programmes ADD COLUMN IF NOT EXISTS cutoff_index NUMERIC(6,2);

-- Minimum UACE grade required in an essential subject. Newly introduced and
-- unvalidated, so failing it routes to review rather than rejection.
ALTER TABLE programmes ADD COLUMN IF NOT EXISTS essential_min_grade VARCHAR(10) DEFAULT 'C';

-- Scheme-level weighting of the admission index. A-level weight is the remainder
-- so the pair always sums to 100.
ALTER TABLE admission_schemes ADD COLUMN IF NOT EXISTS o_level_weight NUMERIC(5,2) DEFAULT 40;
ALTER TABLE admission_schemes ADD COLUMN IF NOT EXISTS a_level_weight NUMERIC(5,2) DEFAULT 60;
ALTER TABLE admission_schemes ADD COLUMN IF NOT EXISTS best_of_o_level INTEGER DEFAULT 8;

-- Grade label counting as an O-level pass for the minimum-passes gate. C6 is the
-- permissive reading; the gate is newly introduced and must not reject anyone
-- against a threshold the committee has not agreed.
ALTER TABLE admission_schemes ADD COLUMN IF NOT EXISTS pass_grade_threshold VARCHAR(10) DEFAULT 'C6';

-- Append-only record of every admission evaluation, for every outcome including
-- rejections. Previously a score was only stored for admitted applicants, so a
-- rejection could not be reviewed, appealed or used as calibration data.
CREATE TABLE IF NOT EXISTS admission_decisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL REFERENCES tenants(id),
  application_id BIGINT NOT NULL REFERENCES applications(id),
  programme_code VARCHAR(200),
  programme_id BIGINT REFERENCES programmes(id),
  outcome VARCHAR(20) NOT NULL,
  admission_index NUMERIC(6,2),
  o_level_index NUMERIC(6,2),
  a_level_index NUMERIC(6,2),
  cutoff_index NUMERIC(6,2),
  legacy_total_score NUMERIC(10,2),
  criteria_json TEXT,
  gates_json TEXT,
  data_quality VARCHAR(200),
  model_version VARCHAR(50),
  scoring_mode VARCHAR(20),
  submitted_at TIMESTAMP,
  human_outcome VARCHAR(20),
  overrode_engine BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_admission_decisions_application ON admission_decisions (application_id);
CREATE INDEX IF NOT EXISTS idx_admission_decisions_programme ON admission_decisions (programme_code, admission_index DESC);
CREATE INDEX IF NOT EXISTS idx_admission_decisions_outcome ON admission_decisions (programme_id, outcome, created_at);

-- Supports the capacity run: one pass over the latest decision per applicant for
-- a programme, ordered for the deterministic tie-break.
CREATE INDEX IF NOT EXISTS idx_admission_decisions_ranking
  ON admission_decisions (programme_code, application_id, admission_index DESC);
